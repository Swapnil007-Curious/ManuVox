"""Build the single-cell Kaggle notebooks in kaggle/ from the repository sources.

kaggle/asl_citizen_extract.ipynb runs without the repository: its one cell holds
src/edgevision/data/citizen_labels.py, the 250 labels of web/public/model/meta.json and
kaggle/asl_citizen_extract.py. kaggle/train_v3.ipynb clones the repository (or unpacks a source
archive) and runs the v3 recipe. Both cells tee everything to a log and always exit 0.

    python scripts/build_kaggle_notebooks.py           # write the notebooks
    python scripts/build_kaggle_notebooks.py --check   # exit 1 when a notebook is stale
    python scripts/build_kaggle_notebooks.py --script-out extract.py  # the extraction program
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LABELS_SOURCE = ROOT / "src" / "edgevision" / "data" / "citizen_labels.py"
EXTRACT_BODY = ROOT / "kaggle" / "asl_citizen_extract.py"
TRAIN_BODY = ROOT / "kaggle" / "train_v3.sh"
META = ROOT / "web" / "public" / "model" / "meta.json"
NOTEBOOKS = {
    "asl_citizen_extract": ROOT / "kaggle" / "asl_citizen_extract.ipynb",
    "train_v3": ROOT / "kaggle" / "train_v3.ipynb",
}
EXTRACT_SETTINGS = {"accelerator": "none", "isGpuEnabled": False, "isInternetEnabled": True}
TRAIN_SETTINGS = {"accelerator": "gpu", "isGpuEnabled": True, "isInternetEnabled": True}


def extraction_program() -> str:
    labels = json.loads(META.read_text(encoding="utf-8"))["labels"]
    return (
        "# Generated by scripts/build_kaggle_notebooks.py; edit the sources, not this cell.\n"
        "# ---- src/edgevision/data/citizen_labels.py ----\n"
        + LABELS_SOURCE.read_text(encoding="utf-8")
        + "\n\n# The 250 labels of web/public/model/meta.json, in model order.\n"
        + f"LABELS = {json.dumps(labels)}\n\n"
        + "# ---- kaggle/asl_citizen_extract.py ----\n"
        + EXTRACT_BODY.read_text(encoding="utf-8")
    )


CREATE_DATASET = r"""
import json, os, subprocess, sys
out = "/kaggle/working/asl-citizen-landmarks"
try:
    from kaggle_secrets import UserSecretsClient
    secrets = UserSecretsClient()
    user, key = secrets.get_secret("KAGGLE_USERNAME"), secrets.get_secret("KAGGLE_KEY")
except Exception as error:
    print("No Kaggle API secrets attached (KAGGLE_USERNAME, KAGGLE_KEY), so no dataset was made.")
    print("Make it from this version's output instead (kaggle/ASL_CITIZEN.md), and keep it Private.")
    sys.exit(0)
env = dict(os.environ, KAGGLE_USERNAME=user, KAGGLE_KEY=key)
path = f"{out}/dataset-metadata.json"
meta = json.load(open(path))
meta["id"] = f"{user}/asl-citizen-landmarks-private"
json.dump(meta, open(path, "w"), indent=1)
if subprocess.run(["kaggle", "--version"], capture_output=True).returncode != 0:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "kaggle"], check=False)
# "datasets create" makes a private dataset unless --public is passed; never pass it.
made = subprocess.run(["kaggle", "datasets", "create", "-p", out, "--dir-mode", "zip"],
                      env=env, capture_output=True, text=True)
print(made.stdout, made.stderr)
if made.returncode != 0 or "already exists" in (made.stdout + made.stderr).lower():
    versioned = subprocess.run(["kaggle", "datasets", "version", "-p", out, "--dir-mode", "zip",
                                "-m", "asl_citizen_extract rerun"], env=env, capture_output=True, text=True)
    print(versioned.stdout, versioned.stderr)
print(f"private dataset: https://www.kaggle.com/datasets/{meta['id']} (check it says Private)")
""".strip()


def extraction_cell() -> str:
    program = extraction_program()
    if "PYEOF" in program:
        raise ValueError("the program must not contain the heredoc marker PYEOF")
    return f"""%%bash
# ASL Citizen -> MediaPipe Holistic landmarks for the 250-sign edge-vision vocabulary.
# Settings: Accelerator None (CPU), Internet On. Run with Save Version > Save & Run All (Commit).
# Resumable: add an earlier version's output as an input and run again; finished shards are
# skipped. Licence: non-commercial research only, never redistribute, keep everything private,
# delete when the research is complete (docs/DATA_LICENSES.md). Generated by
# scripts/build_kaggle_notebooks.py from the repository sources.
set -u
# Parallel parts: three copies of this notebook with 0/3, 1/3 and 2/3, then one run with 0/1
# and the three outputs added as inputs, which merges them and makes the dataset.
export EV_PART="0/1"
WORK=/kaggle/working
LOG="$WORK/asl_citizen_extract.log"
OUT="$WORK/asl-citizen-landmarks"
mkdir -p "$WORK"
{{
  echo "=== $(date -u '+%F %T') UTC: start"
  if [ ! -x /tmp/mpenv/bin/python ]; then
    echo "installing mediapipe==0.10.21 into /tmp/mpenv (a separate venv: it pins numpy<2)"
    python -m venv /tmp/mpenv && /tmp/mpenv/bin/pip install -q --disable-pip-version-check "mediapipe==0.10.21" \\
      || echo "ERROR: could not install mediapipe==0.10.21"
  fi
}} 2>&1 | tee -a "$LOG"
cat > "$WORK/asl_citizen_extract.py" <<'PYEOF'
{program}PYEOF
/tmp/mpenv/bin/python -u "$WORK/asl_citizen_extract.py" 2>&1 | tee -a "$LOG"
echo "=== python exit status ${{PIPESTATUS[0]}}" | tee -a "$LOG"
if [ -f "$OUT/COMPLETE" ]; then
  python - <<'PYEOF' 2>&1 | tee -a "$LOG"
{CREATE_DATASET}
PYEOF
fi
echo "=== $(date -u '+%F %T') UTC: finished; this cell always exits 0, so read $LOG" | tee -a "$LOG"
exit 0
"""


def train_cell() -> str:
    body = TRAIN_BODY.read_text(encoding="utf-8")
    return "%%bash\n" + body


def notebook(cell: str, settings: dict[str, object]) -> str:
    lines = cell.splitlines(keepends=True)
    payload = {
        "cells": [
            {
                "cell_type": "code",
                "execution_count": None,
                "id": "main",
                "metadata": {"trusted": True},
                "outputs": [],
                "source": lines,
            }
        ],
        "metadata": {
            "kaggle": {"language": "python", "sourceType": "notebook", **settings},
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    return json.dumps(payload, indent=1, ensure_ascii=False) + "\n"


def built() -> dict[str, str]:
    return {
        "asl_citizen_extract": notebook(extraction_cell(), EXTRACT_SETTINGS),
        "train_v3": notebook(train_cell(), TRAIN_SETTINGS),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="fail when a notebook is stale")
    parser.add_argument("--script-out", type=Path, help="also write the extraction program here")
    args = parser.parse_args(argv)
    if args.script_out:
        args.script_out.write_text(extraction_program(), encoding="utf-8")
        print(f"wrote {args.script_out}")
    stale = []
    for name, text in built().items():
        path = NOTEBOOKS[name]
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if args.check:
            if current != text:
                stale.append(path.relative_to(ROOT).as_posix())
            continue
        if current != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print(
            f"stale: {', '.join(stale)}; run python scripts/build_kaggle_notebooks.py",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
