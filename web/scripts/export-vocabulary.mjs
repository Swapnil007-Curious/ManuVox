// Writes deploy/worker/src/vocabulary.json, the glosses the translation Worker accepts, from the
// app's sign list (web/src/data/signs.json). The Worker rejects anything else, so no free text can
// reach the model. web/tests/unit/vocabulary.test.ts fails when the two drift.
//
//   node web/scripts/export-vocabulary.mjs

import { readFileSync, writeFileSync } from "node:fs";

const signs = JSON.parse(readFileSync(new URL("../src/data/signs.json", import.meta.url), "utf8")).signs;
const out = new URL("../../deploy/worker/src/vocabulary.json", import.meta.url);
const document = {
  description: "Generated by web/scripts/export-vocabulary.mjs from web/src/data/signs.json; do not edit by hand.",
  glosses: signs.map((sign) => sign.gloss),
};
writeFileSync(out, JSON.stringify(document, null, 1) + "\n");
console.log(`wrote ${document.glosses.length} glosses`);
